// x86_64/core/ofs.h
#ifndef OFS_H
#define OFS_H

#include "../lib/common.h"

// === ОФС: Осирис Файловая Система ===
// Константы раскладки посчитаны скриптом (ofs_math.py) под образ 10 МБ.
// Менять их можно только ВМЕСТЕ с mkofs.py и пересборкой образа!

#define OFS_SUPER_LBA     256   // суперблок (1 сектор)
#define OFS_BITMAP_LBA    257   // битовая карта занятых блоков (8 секторов)
#define OFS_TABLE_LBA     265   // таблица файлов (16 секторов)
#define OFS_DATA_LBA      281   // начало области данных
#define OFS_TABLE_ENTRIES 128   // максимум файлов
#define OFS_ENTRY_SIZE    64    // байт на запись в таблице
#define OFS_NAME_SIZE     48    // байт на имя на диске (UTF-8, до 47 + нуль)
#define OFS_BLOCK_SIZE    512   // блок = сектор

// этап 10: предел размера запускаемой программы (байт)
#define OFS_RUN_MAX       (512 * 1024)

// запись таблицы файлов (смещения, всё little-endian):
//   +0  имя[48]  UTF-8, нуль-терминированное
//   +48 размер  u32
//   +52 старт   u32  номер первого блока данных (0 = первый блок зоны данных)
//   +56 флаг    u8   OFS_FLAG_FILE = файл занят, 0 = запись свободна
#define OFS_FLAG_FILE 1

// суперблок (смещения внутри сектора):
//   +0  магия "OFS1"
//   +4  версия (u8)
//   +5  размер блока (u32)
//   +9  LBA начала данных (u32)
//   +13 всего блоков данных (u32)
//   +17 записей в таблице (u32)

int ofs_mount(void);              // 0 = ОФС подключена, -1 = нет
void ofs_list(void);              // список файлов (команда дир/ls)
int ofs_read(const char *name);   // вывести файл на экран; имя в CP866 (как ввод)
                                  // возвращает размер в байтах или -1
int ofs_load(const char *name, uint32_t load_addr, uint32_t *out_size);
                                  // Этап 10: загрузить файл-программу в память
                                  // по адресу load_addr (блоки по 512 байт подряд).
                                  // имя в CP866 (как ввод); out_size может быть NULL.
                                  // возвращает размер или минус:
                                  // -1 не готова / файла нет / ошибка диска,
                                  // -2 запись битая (за границей данных),
                                  // -4 файл больше OFS_RUN_MAX
int ofs_read_buf(const char *name, char *buf, uint32_t max);
                                  // Этап 12: прочитать файл В БУФЕР (не печатая).
                                  // имя в CP866; копирует size байт, но не больше max.
                                  // возвращает размер или минус:
                                  // -1 не готова / файла нет / ошибка диска / buf NULL,
                                  // -2 запись битая (за границей данных),
                                  // -3 файл больше буфера (size > max)
int ofs_write(const char *name, const char *text); // создать/перезаписать файл
                                  // name в CP866 (как ввод), text - содержимое как есть
                                  // возвращает размер или минус:
                                  // -1 нет места/не готова/ошибка диска,
                                  // -2 имя длиннее 47 байт UTF-8, -3 пустое имя
int ofs_delete(const char *name); // удалить файл; имя в CP866 (как ввод)
                                  // возвращает размер удалённого или -1 (не готова/не найден)
int ofs_append(const char *name, const char *text, int *appended);
                                  // дописать текст в конец файла; нет файла - создать
                                  // appended (если не NULL) - сколько байт дописано сейчас
                                  // возвращает новый размер или минус:
                                  // -1 нет места/не готова/ошибка диска,
                                  // -2/-3 - только при создании (коды ofs_write)
uint32_t ofs_free_blocks(void);   // свободные блоки данных
int ofs_info(const char *name, uint32_t *size, uint32_t *start, uint32_t *nblocks);
                                  // о файле: размер, стартовый блок, число блоков
                                  // (любой из выходных параметров может быть NULL)
                                  // 0 = ок, -1 = не готова / файла нет
void ofs_stats(uint32_t *total, uint32_t *used, uint32_t *files);
                                  // сводка по ОФС: всего блоков данных, занято, файлов
                                  // (если ОФС не готова - все нули)

int ofs_copy(const char *oldname, const char *newname);
                                  // копия файла со всем содержимым; исходный файл остаётся.
                                  // возвращает размер копии или минус:
                                  //   -1 не готова / нет места / таблица полна / ошибка диска,
                                  //   -2 новое имя не подходит, -3 пустое имя,
                                  //   -4 исходного файла нет, -5 новое имя уже занято
int ofs_rename(const char *oldname, const char *newname);
                                  // сменить имя (данные и стартовый блок не трогаются).
                                  // те же коды, 0 = успех (в т.ч. если имя не изменилось)
int ofs_check(void);
                                  // сверка битмапа с таблицей (fsck, только отчёт):
                                  // потерянные блоки, битые записи, двойные блоки,
                                  // мусорные записи. Возвращает число проблем
                                  // (0 = чисто), -1 если ОФС не готова
int ofs_repair(uint32_t *fixed);
                                  // исправить безопасные проблемы: потерянные блоки
                                  // освобождаются, мусорные записи освобождаются,
                                  // заявленные файлом свободные блоки принимаются
                                  // в битмап. *fixed (может быть NULL) - сколько
                                  // исправлено. Возвращает число оставшихся проблем
                                  // (двойные блоки и записи за границей автоматически
                                  // не правятся), -1 если ОФС не готова
#endif
